// Pushes the design tokens the email, PDF and archive HTML use into the backend:
//   backend/app/render/palette.json   (neutral colours + email-safe font stacks)
//   config/genres.yaml                (each genre's theme: accent, accent_soft, rule, fonts)
// tokens.json stays the single source. Run `npm run tokens:backend` after editing it;
// `--check` exits 1 if the backend files are out of date (for CI).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const frontend = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const repo = join(frontend, "..");
const t = JSON.parse(readFileSync(join(frontend, "design", "tokens.json"), "utf8"));
const check = process.argv.includes("--check");

const c = t.colors.light;
const palette = {
  _comment: "GENERATED by frontend/design/scripts/sync-backend.mjs from tokens.json. Do not edit.",
  paper: c.paper,
  paper_raised: c["paper-raised"],
  paper_sunk: c["paper-sunk"],
  ink: c.ink,
  ink_soft: c["ink-soft"],
  ink_muted: c["ink-muted"],
  rule_soft: c["rule-soft"],
  highlight: c.highlight,
  press_red: c["press-red"],
  serif: t.email.serif,
  sans: t.email.sans,
  mono: t.email.mono,
};
const paletteText = JSON.stringify(palette, null, 2) + "\n";

// Genre themes: replace the five theme lines inside each genre's block.
const yamlPath = join(repo, "config", "genres.yaml");
const original = readFileSync(yamlPath, "utf8");
const eol = original.includes("\r\n") ? "\r\n" : "\n";
let genre = null;
const seen = new Set();
const lines = original.split(/\r?\n/).map((line) => {
  const key = line.match(/^\s*-\s+key:\s+(\w+)/);
  if (key) genre = key[1];
  const g = genre && t.genres[genre];
  const field = line.match(/^(\s+)(accent|accent_soft|rule|heading_font|body_font):/);
  if (!g || !field) return line;
  const values = {
    accent: `"${g.accent}"`,
    accent_soft: `"${g.tint}"`,
    rule: `"${c["rule-soft"]}"`,
    heading_font: `"${t.email.serif}"`,
    body_font: `"${t.email.serif}"`,
  };
  seen.add(`${genre}.${field[2]}`);
  return `${field[1]}${field[2]}: ${values[field[2]]}`;
});
const missing = Object.keys(t.genres).flatMap((k) =>
  ["accent", "accent_soft", "rule", "heading_font", "body_font"]
    .filter((f) => !seen.has(`${k}.${f}`))
    .map((f) => `${k}.${f}`),
);
if (missing.length) {
  console.error(`genres.yaml is missing theme fields: ${missing.join(", ")}`);
  process.exit(2);
}
const yamlText = lines.join(eol);

const palettePath = join(repo, "backend", "app", "render", "palette.json");
let current = "";
try {
  current = readFileSync(palettePath, "utf8");
} catch {
  /* first run */
}
const stale = current !== paletteText || original !== yamlText;

if (check) {
  if (stale) {
    console.error("Backend theme files are out of date. Run `npm run tokens:backend`.");
    process.exit(1);
  }
  console.log("Backend theme files are up to date.");
} else {
  writeFileSync(palettePath, paletteText);
  writeFileSync(yamlPath, yamlText);
  console.log(stale ? "updated palette.json and config/genres.yaml" : "already up to date");
}
