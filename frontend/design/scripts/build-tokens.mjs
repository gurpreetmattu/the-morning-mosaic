// Generates src/styles/tokens.css from design/tokens.json.
// Tokens change only in tokens.json; run `npm run tokens` after editing.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const t = JSON.parse(readFileSync(join(root, "design", "tokens.json"), "utf8"));

const vars = (obj, prefix = "") =>
  Object.entries(obj)
    .map(([k, v]) => `  --${prefix}${k}: ${v};`)
    .join("\n");

const darkColors = vars(t.colors.dark);
const genreLight = Object.entries(t.genres)
  .map(([slug, g]) => `[data-genre="${slug}"] { --g-accent: ${g.accent}; --g-tint: ${g.tint}; }`)
  .join("\n");
const genreDark = (sel) =>
  Object.entries(t.genres)
    .map(
      ([slug, g]) =>
        `${sel} [data-genre="${slug}"] { --g-accent: ${g.accentDark}; --g-tint: color-mix(in oklab, ${g.accentDark} 18%, var(--paper)); }`,
    )
    .join("\n");

const css = `/* GENERATED by design/scripts/build-tokens.mjs from design/tokens.json. Do not edit. */
:root {
${vars(t.colors.light)}
${vars(t.fonts, "font-")}
${vars(t.fontSizes, "fs-")}
${t.space.map((px, i) => `  --space-${i + 1}: ${px}px;`).join("\n")}
${vars(t.motion)}
  --radius-0: 0;
  --radius-round: 999px;
  --border-thick: 2px solid var(--ink);
  --rule-hair: 1px solid var(--rule-soft);
  --rule-thin: 1px solid var(--rule);
  --rule-heavy: 4px solid var(--rule);
  --rule-double: 4px double var(--rule);
  --rule-dotted: 2px dotted var(--rule);
  --block-1: 3px 3px 0 var(--ink);
  --block-2: 6px 6px 0 var(--ink);
  --block-genre: 4px 4px 0 var(--g-accent, var(--ink));
  color-scheme: light;
}

/* Late edition: follows the system unless the reader chose Morning. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${darkColors.replace(/^/gm, "  ")}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${darkColors}
  color-scheme: dark;
}

${genreLight}

@media (prefers-color-scheme: dark) {
${genreDark(':root:not([data-theme="light"])').replace(/^/gm, "  ")}
}
${genreDark(':root[data-theme="dark"]')}
`;

writeFileSync(join(root, "src", "styles", "tokens.css"), css);
console.log("wrote src/styles/tokens.css");
